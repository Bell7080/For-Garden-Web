// 인게임 로비 이벤트를 홈페이지에 함께 묶는 스냅샷으로 옮긴다. 화면은 배포된 게임의 최신 피드(/api/events)를
// 먼저 읽고, 이 스냅샷은 그것을 받기 전·받지 못했을 때의 대체이자 원화·SD 정지 이미지를 사이트에 두는 자리다.
// 피드를 굽는 규칙은 게임 저장소 한 곳(For-Garden scripts/build-site-events.mjs)이 갖고, 여기서는 그 결과의
// 파일만 사이트로 복사하고 경로를 바꾼다.
// 사용: npm run sync:events [게임 저장소 경로(기본 ../For-Garden)] [--admin 어드민 저장소 경로]
// 결과: content/game-events.json, public/assets/events/<id>.webp, public/assets/puppets/<id>-sd.zip, (선택) 어드민 shared/game-events.js
import { access, copyFile, mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { tmpdir } from "node:os";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
const execute = promisify(execFile);
const args = process.argv.slice(2);
// --check: 파일을 쓰지 않고 스냅샷이 게임과 같은지만 본다. 게임 저장소가 없으면 건너뛴다(배포 환경).
const check = args.includes("--check") ? (args.splice(args.indexOf("--check"), 1), true) : false;
const adminAt = args.indexOf("--admin");
const adminRoot = adminAt >= 0 ? resolve(args.splice(adminAt, 2)[1]) : undefined;
const game = resolve(args[0] || "../For-Garden");
const builder = resolve(game, "scripts/build-site-events.mjs");
try { await access(builder); await access(resolve(game, "node_modules/esbuild")); } catch {
  if (check) { console.log("게임 저장소(또는 그 의존성)가 없어 이벤트 스냅샷 점검을 건너뜁니다."); process.exit(0); }
  throw new Error(`게임 저장소의 피드 생성기를 찾지 못했습니다: ${builder} (게임 저장소에서 npm ci)`);
}
const temp = await mkdtemp(resolve(tmpdir(), "fg-events-"));
try {
  const out = resolve(temp, "events.json");
  await execute(process.execPath, [builder, "--root", game, "--out", out]);
  const feed = JSON.parse(await readFile(out, "utf8"));
  if (!check) await mkdir("public/assets/events", { recursive: true });
  const bounds = JSON.parse(await readFile("src/puppet-bounds.json", "utf8"));
  const stills = [];
  const events = [];
  for (const e of feed.events) {
    if (!check) await copyFile(resolve(game, "public", e.backdrop.slice(1)), `public/assets/events/${e.id}.webp`);
    let sd = null;
    if (e.sd) {
      const key = `${e.sd.relicId}-sd`;
      if (!check) await copyFile(resolve(game, "public", e.sd.zip.slice(1)), `public/assets/puppets/${key}.zip`);
      bounds[key] = { width: e.sd.width, height: e.sd.height, bounds: e.sd.bounds };
      let still = `/assets/${key}.webp`;
      try { await access(`public${still}`); } catch { stills.push(e.sd.relicId); still = null; }
      sd = { relicId: e.sd.relicId, side: e.sd.side, still, zip: `/assets/puppets/${key}.zip`, bounds: e.sd.bounds };
    }
    events.push({ ...e, backdrop: `/assets/events/${e.id}.webp`, sd });
  }
  const commit = (await execute("git", ["rev-parse", "HEAD"], { cwd: game })).stdout.trim();
  const snapshot = { schema: feed.schema, version: feed.version, commit, rotation: feed.rotation, events };
  if (check) {
    const saved = JSON.parse(await readFile("content/game-events.json", "utf8"));
    const same = JSON.stringify(saved.events) === JSON.stringify(events) && JSON.stringify(saved.rotation) === JSON.stringify(feed.rotation);
    if (!same) {
      console.error("content/game-events.json이 게임의 이벤트와 다릅니다. `npm run sync:events`를 실행하고 함께 커밋하세요.");
      process.exit(1);
    }
    console.log("이벤트 스냅샷이 게임과 같습니다.");
    process.exit(0);
  }
  await writeFile("src/puppet-bounds.json", JSON.stringify(bounds, null, 2).replace(/\[\s+(\d+),\s+(\d+),\s+(\d+),\s+(\d+)\s+\]/g, "[$1, $2, $3, $4]") + "\n");
  await writeFile("content/game-events.json", JSON.stringify(snapshot, null, 2) + "\n");
  if (stills.length) console.warn(`정지 이미지가 없습니다: ${stills.join(", ")} → npm run render:sd-still -- ${stills.join(" ")} 뒤 다시 sync:events`);
  if (adminRoot) {
    const list = events.map((e) => ({ id: e.id, title: e.title.ko, subtitle: e.subtitle.ko, starts_at: e.startsAt, ends_at: e.endsAt, weekly: e.weekly }));
    await writeFile(
      resolve(adminRoot, "shared/game-events.js"),
      `// Snapshot of the game's lobby events (For-Garden src/data/lobbyEvents.ts + ko titles).\n// Generated by For-Garden-Web \`npm run sync:events -- <game> --admin <admin>\`; do not edit by hand.\n// Linking a notice stores only the id and copies the period; edit the period freely.\n// weekly: 정기 이벤트 교대(주 단위) — 기간은 매주 바뀌므로 공지에는 그 주의 기간을 직접 적는다.\nexport const GAME_EVENTS = ${JSON.stringify(list, null, 2)};\n`,
    );
  }
  console.log(`이벤트 ${events.length}개 동기화 (게임 ${snapshot.version})`);
} finally {
  await rm(temp, { recursive: true, force: true });
}
